fun DcColors.toMaterialColorScheme(darkTheme: Boolean): ColorScheme = if (darkTheme) {
    darkColorScheme(
        primary = primaryAction,
        onPrimary = primaryActionContent,
        primaryContainer = waterDeep,
        onPrimaryContainer = waterMist,
        secondary = secondaryAction,
        onSecondary = Color(0xFF002115),
        secondaryContainer = forest.copy(alpha = 0.24f),
        onSecondaryContainer = Color(0xFFD2F8E7),
        tertiary = rock,
        onTertiary = Color(0xFF2F1600),
        background = backgroundBase,
        onBackground = textPrimary,
        surface = surfaceBase,
        onSurface = textPrimary,
        surfaceVariant = surfaceRaised,
        onSurfaceVariant = textSecondary,
        outline = borderStrong,
        outlineVariant = borderSubtle,
        error = riskExtreme,
        onError = Color.White,
    )
} else {
    lightColorScheme(
        primary = primaryAction,
        onPrimary = primaryActionContent,
        primaryContainer = waterMist,
        onPrimaryContainer = Color(0xFF07333B),
        secondary = secondaryAction,
        onSecondary = Color.White,
        secondaryContainer = Color(0xFFD9F0E2),
        onSecondaryContainer = Color(0xFF06351F),
        tertiary = rock,
        onTertiary = Color.White,
        background = backgroundBase,
        onBackground = textPrimary,
        surface = surfaceBase,
        onSurface = textPrimary,
        surfaceVariant = surfaceRaised,
        onSurfaceVariant = textSecondary,
        outline = borderStrong,
        outlineVariant = borderSubtle,
        error = riskExtreme,
        onError = Color.White,
    )
}

